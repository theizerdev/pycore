"""
Capa 2A del Agente Clínico Propio (MediCore AI Local):
Base de Conocimiento Bioquímico de 105+ Biomarcadores Clínicos organizados en 14 paneles,
con rangos de referencia dinámicos por Sexo y Edad, umbrales críticos de pánico clínico,
normalización de unidades y cotas fisiológicas anti-falsos positivos.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple


@dataclass(frozen=True)
class BiomarkerSpec:
    key: str
    nombre: str
    panel: str
    pattern: str
    unidad: str
    ref_default: Tuple[float, float]
    ref_male: Optional[Tuple[float, float]] = None
    ref_female: Optional[Tuple[float, float]] = None
    ref_pediatric: Optional[Tuple[float, float]] = None
    critical_low: Optional[float] = None
    critical_high: Optional[float] = None
    plausible: Tuple[float, float] = (0.0, 1_000_000.0)
    scale_mode: Optional[str] = None  # 'k_to_mm3' | 'gluc_mmol' | 'chol_mmol' | 'tg_mmol' | 'creat_umol' | 'pct_cap'
    high_hint: str = "Valor por encima del intervalo biológico de referencia."
    low_hint: str = "Valor por debajo del intervalo biológico de referencia."


def resolve_reference_range(
    spec: BiomarkerSpec,
    genero: Optional[str] = None,
    edad: Optional[int] = None,
) -> Tuple[float, float, bool]:
    """
    Devuelve (ref_min, ref_max, es_personalizado) ajustado a edad y sexo del paciente.
    """
    g = (genero or "").strip().upper()
    if edad is not None and edad < 14 and spec.ref_pediatric is not None:
        return spec.ref_pediatric[0], spec.ref_pediatric[1], True
    if g in ("M", "MASCULINO", "HOMBRE", "MALE") and spec.ref_male is not None:
        return spec.ref_male[0], spec.ref_male[1], True
    if g in ("F", "FEMENINO", "MUJER", "FEMALE") and spec.ref_female is not None:
        return spec.ref_female[0], spec.ref_female[1], True
    return spec.ref_default[0], spec.ref_default[1], False


